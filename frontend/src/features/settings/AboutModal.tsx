// About modal: a hero with the logo, version, license and copyright, then two tabs: the license (the full text of LICENSE)
// and the open-source software the app uses, in one list filtered by part or by a search, where each row shows its license
// text in place and opens its homepage. The dialog keeps one size on both tabs.
import { Info, MagnifyingGlass, Scales } from '@phosphor-icons/react';
import { useEffect, useMemo, useState } from 'react';
import { backend } from '@/backend';
import { t } from '@/i18n';
import { devLog } from '@/state/devLog';
import { useNodePacks } from '@/state/comfy/nodePacks';
import { toast } from '@/state/toasts';
import { useUi } from '@/state/ui';
import { Badge, ErrorBoundary, Modal, Tab, TabList, TabPanel, Tabs, TextInput } from '@/ui';
import oss from './ossLicenses.json';
import { homepageOf, ossKey, parseOssTexts } from './ossTexts';
import licenseNotice from '../../../../NOTICE?raw';

import { APP_VERSION } from '@/state/appVersion';

const VERSION = APP_VERSION;
const LICENSE_ID = 'Apache-2.0';
/** The copyright line of NOTICE, shown in the hero. */
const COPYRIGHT = licenseNotice.split(/\r?\n/).find((l) => l.startsWith('Copyright'))?.replace(/^Copyright/, '©') ?? '';

interface OssEntry {
  name: string;
  version: string;
  url: string;
}

type GroupId = 'frontend' | 'backend' | 'engine' | 'packs';

/** Parts in the order they are shown; the lists themselves are generated by `npm run licenses`. */
const GROUPS = [
  { id: 'frontend', labelKey: 'settings.about.oss.short.frontend', titleKey: 'settings.about.oss.frontend', entries: oss.frontend as OssEntry[] },
  { id: 'backend', labelKey: 'settings.about.oss.short.backend', titleKey: 'settings.about.oss.backend', entries: oss.backend as OssEntry[] },
  { id: 'engine', labelKey: 'settings.about.oss.short.engine', titleKey: 'settings.about.oss.engine', entries: oss.engine as OssEntry[] },
] as const;

/** The extensions installed right now (ComfyUI itself is listed under the engine); null until loaded. */
function useInstalledPacks(): OssEntry[] | null {
  const packs = useNodePacks((s) => s.packs?.installed);
  const load = useNodePacks((s) => s.load);
  useEffect(() => {
    void load();
  }, [load]);
  return useMemo(
    () =>
      packs?.map((p) => ({ name: p.folder, version: '', url: p.url ?? '' })) ?? null,
    [packs],
  );
}

// The license texts are large, so each is loaded only when it is shown (a separate chunk, out of the main bundle).
const readLicense = () => import('../../../../LICENSE?raw').then((m) => m.default);
const readNotices = () => import('../../../../THIRD_PARTY_NOTICES.txt?raw').then((m) => m.default);

/** Each package's texts out of the notices, read once for every row that asks. */
let ossTexts: Promise<Map<string, string[]>> | null = null;
const readOssTexts = () => (ossTexts ??= readNotices().then(parseOssTexts));
/** Between two texts of one package (a license and a notice). */
const TEXT_RULE = `\n\n${'-'.repeat(70)}\n\n`;

/** The system browser opens the page, after the backend has checked the address (a link would do nothing in the desktop window). */
function openHomepage(url: string) {
  const page = homepageOf(url);
  if (backend.kind === 'mock') {
    toast({ status: 'info', title: t('settings.about.oss.openMock'), description: page }, 2200);
    return;
  }
  backend.openSourcePage(page).catch((e: unknown) => {
    toast({ status: 'error', title: t('settings.about.oss.openFailed'), description: e instanceof Error ? e.message : String(e) });
  });
}

/** One package: its name and version, with its license text shown in place and a link to its homepage. */
function OssRow({ entry }: { entry: OssEntry }) {
  const [open, setOpen] = useState(false);
  const read = useMemo(() => () => readOssTexts().then((texts) => texts.get(ossKey(entry.name, entry.version))?.join(TEXT_RULE) ?? null), [entry]);
  return (
    <li className="ab-row">
      <div className="ab-row__head">
        <span className="ab-row__name">{entry.name}</span>
        {entry.version && <span className="ab-row__version">{entry.version}</span>}
        <span className="ab-row__links">
          <button type="button" className="ab-link" aria-expanded={open} onClick={() => setOpen(!open)}>
            {open ? t('settings.about.oss.hideLicense') : t('settings.about.oss.showLicense')}
          </button>
          {entry.url && (
            <button type="button" className="ab-link" title={homepageOf(entry.url)} onClick={() => openHomepage(entry.url)}>
              {t('settings.about.oss.homepage')}
            </button>
          )}
        </span>
      </div>
      {open && <LicenseText read={read} label={t('settings.about.oss.licenseFor', { name: entry.name })} inline />}
    </li>
  );
}

function OssPanel() {
  const packs = useInstalledPacks();
  const [group, setGroup] = useState<GroupId | 'all'>('all');
  const [query, setQuery] = useState('');

  const groups = useMemo(
    () => [
      ...GROUPS.map((g) => ({ id: g.id as GroupId, label: t(g.labelKey), title: t(g.titleKey), entries: g.entries })),
      ...(packs ? [{ id: 'packs' as const, label: t('settings.about.oss.short.packs'), title: t('settings.about.packs.title'), entries: packs }] : []),
    ],
    [packs],
  );
  const inGroup = useMemo(() => {
    const list = group === 'all' ? groups.flatMap((g) => g.entries) : (groups.find((g) => g.id === group)?.entries ?? []);
    return group === 'all' ? [...list].sort((a, b) => a.name.localeCompare(b.name)) : list;
  }, [group, groups]);
  const shown = useMemo(() => {
    const q = query.trim().toLowerCase();
    return q ? inGroup.filter((e) => e.name.toLowerCase().includes(q)) : inGroup;
  }, [inGroup, query]);
  const total = groups.reduce((n, g) => n + g.entries.length, 0);

  return (
    <div className="ab-panel" data-testid="about-oss">
      <p className="ab-text">{t('settings.about.oss.intro')}</p>
      <div className="ab-filters">
        <div className="ab-chips" role="group" aria-label={t('settings.about.oss.groupLabel')}>
          <button type="button" className="ab-chip" aria-pressed={group === 'all'} onClick={() => setGroup('all')}>
            {t('settings.about.oss.all')}
            <span className="ab-chip__count">{total}</span>
          </button>
          {groups.map((g) => (
            <button key={g.id} type="button" className="ab-chip" aria-pressed={group === g.id} title={g.title} onClick={() => setGroup(g.id)}>
              {g.label}
              <span className="ab-chip__count">{g.entries.length}</span>
            </button>
          ))}
        </div>
        <label className="ab-search">
          <MagnifyingGlass size={14} className="ab-search__icon" />
          <TextInput value={query} onChange={(e) => setQuery(e.target.value)} placeholder={t('settings.about.oss.search')} aria-label={t('settings.about.oss.search')} />
        </label>
      </div>
      <div className="ab-list" data-testid="about-oss-list" tabIndex={0}>
        {shown.length === 0 ? (
          <p className="ab-list__empty">{inGroup.length === 0 ? t('settings.about.packs.none') : t('settings.about.oss.noMatch')}</p>
        ) : (
          <ul>
            {shown.map((e) => (
              <OssRow key={`${e.name}@${e.version}`} entry={e} />
            ))}
          </ul>
        )}
      </div>
      <p className="ab-footnote">{t('settings.about.oss.packsNote')}</p>
    </div>
  );
}

/**
 * A license text, read the first time it is shown. `read` gives null when there is no text (software the app downloads
 * later, an extension): its homepage has it. `inline` is the box under a row of the open-source list; otherwise the text
 * fills the license tab.
 */
function LicenseText({ read, label, inline = false }: { read: () => Promise<string | null>; label: string; inline?: boolean }) {
  const [text, setText] = useState<string | null | undefined>(undefined);
  const [failed, setFailed] = useState(false);
  useEffect(() => {
    let live = true;
    setText(undefined);
    setFailed(false);
    read().then(
      (s) => {
        if (live) setText(s);
      },
      (err: unknown) => {
        devLog('error', 'about', `license text: ${String(err)}`);
        if (live) setFailed(true);
      },
    );
    return () => {
      live = false;
    };
  }, [read]);
  if (failed) return <p className="ab-text">{t('settings.about.license.failed')}</p>;
  if (text === undefined) return <p className="ab-text">{t('settings.about.license.loading')}</p>;
  if (text === null) return <p className="ab-text">{t('settings.about.oss.textAtHomepage')}</p>;
  return (
    <pre className={inline ? 'ab-license ab-license--inline' : 'ab-license'} data-testid="about-license-text" tabIndex={0} aria-label={label}>
      {text}
    </pre>
  );
}

function LicensePanel() {
  return (
    <div className="ab-panel" data-testid="about-license">
      <p className="ab-text">{t('settings.about.license.intro')}</p>
      <LicenseText read={readLicense} label={t('settings.about.license.novira')} />
    </div>
  );
}

export function AboutModal(_props: { tab?: unknown }) {
  const open = useUi((s) => s.modal === 'about');
  const openModal = useUi((s) => s.openModal);
  const [tab, setTab] = useState('license');
  if (!open) return null;
  const mock = backend.kind === 'mock';
  return (
    <Modal open onOpenChange={(o) => !o && openModal(null)} title={t('settings.about.title')} size="lg" closeLabel={t('common.close')}>
      <div className="ab" data-testid="about-modal">
        <div className="ab-hero">
          <div className="ab-logo">novira</div>
          <div className="ab-meta">
            <span className="ab-meta__item">
              <span className="ab-meta__label">{t('settings.about.version')}</span>
              <Badge scheme="accent">{mock ? `${VERSION} (mock)` : VERSION}</Badge>
            </span>
            <span className="ab-meta__item">
              <Scales size={14} />
              {LICENSE_ID}
            </span>
            {COPYRIGHT && <span className="ab-meta__item">{COPYRIGHT}</span>}
          </div>
        </div>
        <Tabs value={tab} onValueChange={setTab} className="ab-tabs">
          <TabList>
            <Tab value="license">{t('settings.about.license.title')}</Tab>
            <Tab value="oss">{t('settings.about.oss.title')}</Tab>
          </TabList>
          <TabPanel value="license" className="ab-tabs__panel">
            <ErrorBoundary area="about license" variant="panel">
              <LicensePanel />
            </ErrorBoundary>
          </TabPanel>
          <TabPanel value="oss" className="ab-tabs__panel">
            <ErrorBoundary area="about open source" variant="panel">
              <OssPanel />
            </ErrorBoundary>
          </TabPanel>
        </Tabs>
        {mock && (
          <div className="ab-note">
            <Info size={16} />
            <span>{t('settings.about.mockNote')}</span>
          </div>
        )}
      </div>
    </Modal>
  );
}
